SOLID = set('#~')


def parse(grid: str):
    rows = [r for r in grid.strip('\n').split('\n')]
    assert len(rows) == H, f'altura {len(rows)} != {H}'
    for i, r in enumerate(rows):
        assert len(r) == W, f'linha {i} com {len(r)} colunas: {r!r}'
    return rows


def reach(rows, start):
    seen = set([start]); q = deque([start])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and rows[ny][nx] not in SOLID:
                seen.add((nx, ny)); q.append((nx, ny))
    return seen


def paint(rows, plazas):
    """Aplica as camadas autorais: praças de blocos ('=') nos retângulos indicados e trilhas com 2 tiles de largura."""
    g = [list(r) for r in rows]
    for y in range(H):
        for x in range(W):
            if rows[y][x] == ',' and y + 1 < H and rows[y + 1][x] == '.':
                g[y + 1][x] = ','
    for (px, py, pw, ph) in plazas:
        for y in range(py, py + ph):
            for x in range(px, px + pw):
                if g[y][x] not in SOLID:
                    g[y][x] = '='
    return [''.join(r) for r in g]


def main():
    os.makedirs(OUT, exist_ok=True)
    for key, m in MAPS.items():
        rows = paint(parse(m['grid']), m.get('plazas', []))
        ok = reach(rows, tuple(m['start']))
        for label in ('anchor', 'portal', 'elite', 'boss'):
            if label in m:
                assert tuple(m[label]) in ok, f'{key}: {label} {m[label]} inalcançável/sólido'
        walk = sum(1 for y in range(H) for x in range(W) if rows[y][x] not in SOLID)
        assert len(ok) == walk, f'{key}: {walk - len(ok)} tiles caminháveis isolados'
        for (x, y, w, h) in m['spawns']:
            cells = [(cx, cy) for cy in range(y, y + h) for cx in range(x, x + w) if (cx, cy) in ok]
            assert len(cells) >= max(1, w * h // 3), f'{key}: zona de spawn {(x, y, w, h)} quase toda sólida'
        data = {
            'name': m['name'], 'tileset': m['tileset'], 'tileSize': T, 'width': W, 'height': H,
            'rows': rows, 'start': m['start'], 'anchor': m['anchor'], 'portal': m['portal'], 'elite': m['elite'],
            'boss': m.get('boss'), 'props': m['props'], 'spawns': m['spawns'],
        }
        with open(os.path.join(OUT, key + '.json'), 'w') as f:
            json.dump(data, f, ensure_ascii=False, indent=0)
        print(f'{key}: ok — {walk} tiles caminháveis, {len(m["props"])} props, {len(m["spawns"])} zonas de spawn')


if __name__ == '__main__':
    main()
